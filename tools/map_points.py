"""The in-game map tracker's places (Savage Wind runtime/ui/ap_client.mm map_draw): every location with a place on the
map, as {flag hash (= its id - LOC_BASE), x, z, kind} -> runtime/ui/ap_map_points.inc. Run after locations.json changes.
Usage: python tools/map_points.py <SavageWindRecomp folder>"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
# kind: the marker's colour in ap_client.mm (KIND_COLOURS, same order)
KINDS = ["Shrine", "Korok", "Chest", "Shop", "Quest", "Tower", "Other"]
KIND_OF = {"Shrine": "Shrine", "Shrine Chest": "Shrine", "Shrine Quest": "Quest", "Rune Terminal": "Shrine",
           "Korok": "Korok", "Chest": "Chest", "Divine Beast Chest": "Chest", "Shop": "Shop", "Hestu": "Shop",
           "Side Quest": "Quest", "Main Quest": "Quest", "Memory": "Quest", "Divine Beast": "Quest",
           "Tower": "Tower", "Minigame": "Other", "Rune Upgrade": "Other"}


def main(out_root):
    locs = json.loads((HERE / "worlds/botw/data/locations.json").read_text(encoding="utf-8"))
    shrine_pos = {l["name"]: l["pos"] for l in locs if l["category"] == "Shrine" and l.get("pos")}

    def where(l):  # (as tools/poptracker.py: a shrine's or Divine Beast's insides are maps of their own)
        if l.get("spot"):
            return l["spot"]
        if l["category"] in ("Shrine Chest", "Rune Terminal"):
            return shrine_pos.get(l["name"].split(" Chest")[0].replace(" Terminal", ""))
        return l.get("pos")

    rows = [(l["hash"], p[0], p[1], KINDS.index(KIND_OF.get(l["category"], "Other")))
            for l in locs if (p := where(l))]
    out = pathlib.Path(out_root) / "runtime/ui/ap_map_points.inc"
    out.write_text("// generated by botw_ap tools/map_points.py from worlds/botw/data/locations.json: {flag hash, x, z, kind}\n" +
                   "".join(f"{{0x{h:08x}u, {x}, {z}, {k}}},\n" for h, x, z, k in rows), encoding="utf-8", newline="\n")
    print(f"{len(rows)} places -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
