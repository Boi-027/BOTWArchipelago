"""The in-game map tracker's places and logic (Savage Wind runtime/ui/ap_client.mm map_draw), from worlds/botw:
- runtime/ui/ap_map_points.inc: every location with a place on the map, as {flag hash (= its id - LOC_BASE), x, z,
  kind, region, needs, seeds, rune, freed}: what it needs in logic, as tools/poptracker.py's rule() has it
- runtime/ui/ap_map_logic.inc: the items those needs name (their ids), the region graph, the Divine Beasts' checks
Run after locations.json, regions.json or the world's logic changes.
Usage: python tools/map_points.py <SavageWindRecomp folder>"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(HERE / "tools"), str(HERE / "launcher")]
import poptracker  # noqa: E402  (its rule(): the world's logic as data)

# kind: the marker's icon in ap_client.mm (tools/map_icons.py ART, same order)
KINDS = ["Shrine", "Korok", "Chest", "Shop", "Quest", "Tower", "Other"]
KIND_OF = {"Shrine": "Shrine", "Shrine Chest": "Shrine", "Shrine Quest": "Quest", "Rune Terminal": "Shrine",
           "Korok": "Korok", "Chest": "Chest", "Divine Beast Chest": "Chest", "Shop": "Shop", "Hestu": "Shop",
           "Side Quest": "Quest", "Main Quest": "Quest", "Memory": "Quest", "Divine Beast": "Quest",
           "Tower": "Tower", "Minigame": "Other", "Rune Upgrade": "Other"}
# a rule's yes/no needs, as bits (ap_client.mm NEED_*)
NEED_BITS = ["glider", "trial", "powers", "pull", "maracas"]
# the items a check's own needs name (tools/poptracker.py codes; ap_client.mm LG_ITEMS, same order): masks of these
ITEM_CODES = ["remote_bomb", "magnesis", "stasis", "cryonis", "flamebreaker", "gerudo_set", "zora_armor"]
ITEM_NAMES = ["Progressive Remote Bomb", "Magnesis", "Progressive Stasis", "Cryonis", "Flamebreaker Set", "Gerudo Set",
              "Zora Armor"]


def main(out_root):
    locs = json.loads((HERE / "worlds/botw/data/locations.json").read_text(encoding="utf-8"))
    regions = json.loads((HERE / "worlds/botw/data/regions.json").read_text(encoding="utf-8"))
    poptracker.SHRINE_DUNGEON.update({l["name"]: l["dungeon"] for l in locs if l["category"] == "Shrine"})
    shrine_pos = {l["name"]: l["pos"] for l in locs if l["category"] == "Shrine" and l.get("pos")}
    beasts = poptracker.BEASTS

    def where(l):  # (as tools/poptracker.py: a shrine's or Divine Beast's insides are maps of their own)
        if l.get("spot"):
            return l["spot"]
        if l["category"] in ("Shrine Chest", "Rune Terminal"):
            return shrine_pos.get(l["name"].split(" Chest")[0].replace(" Terminal", ""))
        return l.get("pos")

    rows = []
    for l in locs:
        if not (p := where(l)):
            continue
        r = poptracker.rule(l)
        need = sum(1 << i for i, k in enumerate(NEED_BITS) if r.get(k))
        freed = sum(1 << beasts.index(b) for b in r.get("freed", []))
        mask = lambda codes: sum(1 << ITEM_CODES.index(c) for c in codes)
        rows.append(f"{{0x{l['hash']:08x}u, {p[0]}, {p[1]}, {KINDS.index(KIND_OF.get(l['category'], 'Other'))}, "
                    f"{r['reg']}, {need}, {r.get('seeds', 0)}, {mask(r.get('items', []))}, {mask(r.get('any', []))}, "
                    f"{freed}}},\n")
    root = pathlib.Path(out_root) / "runtime/ui"
    (root / "ap_map_points.inc").write_text(
        "// generated by botw_ap tools/map_points.py from worlds/botw: {flag hash, x, z, kind, region, needs, seeds, "
        "items all, items any, beasts freed}\n" + "".join(rows), encoding="utf-8", newline="\n")

    ids = poptracker.item_ids()
    powers = [n for n in ids if n.startswith("Progressive ") and n.split(" ", 1)[1].split("'")[0] in
              ("Mipha", "Daruk", "Revali", "Urbosa")]
    assert len(powers) == 4, powers
    by_hash = {l["name"]: l["hash"] for l in locs}
    names = regions["names"]
    adj = ", ".join("{" + ", ".join(str(j) for j in (a + [-1] * 8)[:8]) + "}" for a in regions["adjacent"])
    maps = ", ".join(str(ids[f"{n} Map"]) if f"{n} Map" in ids else "0" for n in names)
    one = lambda n: f"{ids[n]}LL"
    (root / "ap_map_logic.inc").write_text(f"""// generated by botw_ap tools/map_points.py from worlds/botw: the items its logic names, its regions
const int64_t LG_PARAGLIDER = {one("Paraglider")}, LG_MARACAS = {one("Hestu's Maracas")}, LG_KOROK = {one("Korok Seed")},
              LG_HEART = {one("Heart Container")}, LG_SWORD = {one("Progressive Master Sword")},
              LG_HELM = {one("Thunder Helm")}, LG_ZORA = {one("Zora Armor")};
const int64_t LG_RUNES[4] = {{{", ".join(one(n) for n in ["Progressive Remote Bomb", "Magnesis", "Progressive Stasis", "Cryonis"])}}};
const int64_t LG_ITEMS[{len(ITEM_NAMES)}] = {{{", ".join(one(n) for n in ITEM_NAMES)}}};  // (the items masks' bits)
const int64_t LG_POWERS[4] = {{{", ".join(one(n) for n in powers)}}};
const int64_t LG_MAPS[{len(names)}] = {{{maps}}};  // (each region's map; 0: the Great Plateau's, none)
const int LG_PLATEAU = {regions["plateau"]};
const int8_t LG_ADJACENT[{len(names)}][8] = {{{adj}}};
const uint32_t LG_CLEARED[4] = {{{", ".join(f"0x{by_hash[b + ' Cleared']:08x}u" for b in beasts)}}};
const char *const LG_BEASTS[4] = {{{", ".join(f'"{b}"' for b in beasts)}}};
const char *const LG_REGIONS[{len(names)}] = {{{", ".join(f'"{n}"' for n in names)}}};
""", encoding="utf-8", newline="\n")
    print(f"{len(rows)} places -> {root / 'ap_map_points.inc'}, logic -> {root / 'ap_map_logic.inc'}")


if __name__ == "__main__":
    main(sys.argv[1])
